export function translateWebStringToEn(raw) {
  if (!raw || typeof raw !== 'string') return raw;
  const trimmed = raw.trim();
  if (!trimmed || !/[\u0600-\u06FF]/.test(trimmed)) return raw;

  const lead = raw.match(/^\s*/)?.[0] || '';
  const trail = raw.match(/\s*$/)?.[0] || '';

  if (WEB_EXACT_DICTIONARY[trimmed]) {
    return `${lead}${WEB_EXACT_DICTIONARY[trimmed]}${trail}`;
  }

  // Bilingual medicine names like "بنادول إكسترا (Panadol Extra)" -> "Panadol Extra"
  const bilingualMedMatch = trimmed.match(/^[\u0600-\u06FF0-9\s]+\(([A-Za-z0-9\s\-+/.%]+)\)$/);
  if (bilingualMedMatch) {
    return `${lead}${bilingualMedMatch[1].trim()}${trail}`;
  }

  // Dynamic patterns
  let out = trimmed;

  // Doctor names "د. ..."
  if (/^د\.\s+/.test(out)) {
    const rest = out.replace(/^د\.\s+/, '').trim();
    const mappedDoc = DOCTOR_NAME_SUB_MAP[rest] || rest;
    return `${lead}Dr. ${mappedDoc}${trail}`;
  }

  // Compound locations like "القاهرة - المعادي" or split "- المعادي"
  if (out.startsWith('- ')) {
    const sub = out.slice(2).trim();
    const mapped = CITY_SUB_MAP[sub] || WEB_EXACT_DICTIONARY[sub];
    if (mapped) return `${lead}- ${mapped}${trail}`;
  }

  if (out.includes(' - ')) {
    const parts = out.split(' - ').map((p) => CITY_SUB_MAP[p.trim()] || WEB_EXACT_DICTIONARY[p.trim()] || p.trim());
    if (!/[\u0600-\u06FF]/.test(parts.join(' - '))) {
      return `${lead}${parts.join(' - ')}${trail}`;
    }
  }

  // Doctor dropdown option: "د. أحمد الشناوي (عظام) - 250 ج.م"
  const docOptMatch = out.match(/^د\.\s*([^(]+)\(([^)]+)\)\s*-\s*([\d,.]+)\s*ج\.م$/);
  if (docOptMatch) {
    const dName = DOCTOR_NAME_SUB_MAP[docOptMatch[1].trim()] || docOptMatch[1].trim();
    const dSpec = WEB_EXACT_DICTIONARY[docOptMatch[2].trim()] || docOptMatch[2].trim();
    return `${lead}Dr. ${dName} (${dSpec}) - ${docOptMatch[3]} EGP${trail}`;
  }

  out = out
    .replace(/^كشف:\s*([\d,.]+)\s*ج\.م$/, 'Fee: $1 EGP')
    .replace(/^كشف:$/, 'Fee:')
    .replace(/^([\d,.]+)\s*ج\.م\s*\/\s*العبوة$/, '$1 EGP / Pack')
    .replace(/^([\d,.]+)\s*ج\.م$/, '$1 EGP')
    .replace(/^ج\.م$/, 'EGP')
    .replace(/^متبقي\s+(\d+)\s+فقط$/, 'Only $1 left')
    .replace(/^متوفر بالمخزون\s*\(([^)]+)\)$/, (_, c) => `In Stock (${c === 'متاح' ? 'Available' : c})`)
    .replace(/^أضف\s+([\d,.]+)\s*ج\.م\s+للحصول على توصيل مجاني$/, 'Add $1 EGP for free delivery')
    .replace(/^خطوة\s+(\d+)\s+من\s+(\d+)$/, 'Step $1 of $2')
    .replace(/^\((\d+)\s*تقييم\)$/, '($1 reviews)')
    .replace(/^(\d+)\s*تقييم$/, '$1 reviews')
    .replace(/^(\d+)\s+رسالة$/, '$1 messages')
    .replace(/^صورة\s+(\d+)$/, 'Photo $1')
    .replace(/^عيادة د\.\s*(.+?)\s+(\d+)$/, (_, n, idx) => `Dr. ${DOCTOR_NAME_SUB_MAP[n.trim()] || n.trim()} Clinic ${idx}`)
    .replace(/^صفحة\s+(\d+)\s+من\s+(\d+)$/, 'Page $1 of $2')
    .replace(/^المتابعة القادمة:\s*(.+)$/, 'Next follow-up: $1')
    .replace(/^تحديث:\s*(.+)$/, 'Updated: $1')
    .replace(/^•\s*المدة:\s*(.+)$/, '• Duration: $1');

  return `${lead}${out}${trail}`;
}
