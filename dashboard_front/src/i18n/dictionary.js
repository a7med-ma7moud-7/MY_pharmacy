export function translateAdminStringToEn(raw) {
  if (!raw || typeof raw !== 'string') return raw;
  const trimmed = raw.trim();
  if (!trimmed || !/[\u0600-\u06FF]/.test(trimmed)) return raw;

  const lead = raw.match(/^\s*/)?.[0] || '';
  const trail = raw.match(/\s*$/)?.[0] || '';

  if (ADMIN_EXACT_DICTIONARY[trimmed]) {
    return `${lead}${ADMIN_EXACT_DICTIONARY[trimmed]}${trail}`;
  }

  // Bilingual medicine names "بنادول إكسترا (Panadol Extra)"
  const bilingualMed = trimmed.match(/^[\u0600-\u06FF0-9\s]+\(([A-Za-z0-9\s\-+/.%]+)\)$/);
  if (bilingualMed) {
    return `${lead}${bilingualMed[1].trim()}${trail}`;
  }

  if (/^د\.\s+/.test(trimmed)) {
    const rest = trimmed.replace(/^د\.\s+/, '').trim();
    return `${lead}Dr. ${DOCTOR_NAME_MAP[rest] || rest}${trail}`;
  }

  if (DOCTOR_NAME_MAP[trimmed]) {
    return `${lead}${DOCTOR_NAME_MAP[trimmed]}${trail}`;
  }

  if (trimmed.startsWith('- ')) {
    const sub = trimmed.slice(2).trim();
    if (ADMIN_EXACT_DICTIONARY[sub]) {
      return `${lead}- ${ADMIN_EXACT_DICTIONARY[sub]}${trail}`;
    }
  }

  if (trimmed.includes(' - ')) {
    const parts = trimmed.split(' - ').map((p) => ADMIN_EXACT_DICTIONARY[p.trim()] || p.trim());
    if (!/[\u0600-\u06FF]/.test(parts.join(' - '))) {
      return `${lead}${parts.join(' - ')}${trail}`;
    }
  }

  let out = trimmed
    .replace(/^مرحباً بك مجدداً،\s*(.+)$/, 'Welcome back, $1')
    .replace(/^إعادة تعيين كلمة مرور:\s*(.+)$/, 'Reset Password: $1')
    .replace(/^تعديل المستخدم:\s*(.+)$/, 'Edit User: $1')
    .replace(/^تعديل بيانات الطبيب:\s*(.+)$/, 'Edit Doctor: $1')
    .replace(/^تعديل صنف الدواء:\s*(.+)$/, 'Edit Medicine: $1')
    .replace(/^تعديل كمية المخزون:\s*(.+)$/, 'Update Stock: $1')
    .replace(/^صنف\s*#(\d+)$/, 'Item #$1')
    .replace(/^طبيب\s*#(.+)$/, 'Doctor #$1')
    .replace(/^صورة\s+(\d+)$/, 'Photo $1')
    .replace(/^([\d,.]+)\s*ج\.م$/, '$1 EGP')
    .replace(/^ج\.م$/, 'EGP')
    .replace(/^(\d+)\s+عبوة$/, '$1 packs')
    .replace(/^(\d+)\s+صنف$/, '$1 items')
    .replace(/^(\d+)\s+رسالة\s*\(([^)]+)\)$/, '$1 msgs ($2)')
    .replace(/^(\d+)\s+رسالة$/, '$1 messages')
    .replace(/^(\d+)\s+نشطة\s*\|\s*(\d+)\s+محذوفة$/, '$1 active | $2 deleted')
    .replace(/^اليوم:\s*(\d+)\s*\|\s*هذا الشهر:\s*(\d+)$/, 'Today: $1 | This Month: $2')
    .replace(/^أخطاء:\s*(\d+)\s*\|\s*محظورة أمنياً:\s*(\d+)$/, 'Failed: $1 | Blocked: $2')
    .replace(/^إيجابي:\s*(\d+)\s*\|\s*سلبي:\s*(\d+)$/, 'Positive: $1 | Negative: $2')
    .replace(/^\(إجمالي العناصر:\s*(\d+)\)$/, '(Total items: $1)')
    .replace(/^طلبات تسجيل الأطباء\s*\((\d+)\)$/, 'Doctor Verification Requests ($1)')
    .replace(/^متوفر\s*\((\d+)\s*عبوة\)$/, 'In Stock ($1 packs)')
    .replace(/^مخزون منخفض\s*\((\d+)\s*عبوة\)$/, 'Low Stock ($1 packs)')
    .replace(/^تفاصيل الحجز الطبي\s*#(\d+)$/, 'Appointment Details #$1')
    .replace(/^فاتورة تفاصيل الطلب\s*#(\d+)$/, 'Order Invoice #$1')
    .replace(/^لا يُمنح مشرفو النظام وصولاً تلقائياً.+$/, 'Administrators do not receive automatic access to private patient conversation transcripts or medical records. Only operational telemetry and masked metadata are shown, with full audit logging.')
    .replace(/^المحرك الطبي الهجين.+$/, 'Bilingual hybrid clinical + authorized records engine is active.')
    .replace(/^المفتاح الحالي مرفوض من المزود.+$/, 'Provider key rejected (403) — hybrid clinical engine is serving safely as automatic failover.')
    .replace(/^اختياري — غير مُعد حالياً\.$/, 'Optional — not configured yet.');

  return `${lead}${out}${trail}`;
}
